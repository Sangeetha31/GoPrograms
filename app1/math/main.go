package main

import (
	"fmt"
	"math"
)

func main() {

	fmt.Println(math.Pow(2, 3))
	fmt.Println(math.Sin(10.25))
	fmt.Println(math.Abs(-10.5))
	fmt.Println(math.Floor(10.2))
	fmt.Println(math.Floor(10.9))
	fmt.Println(math.Ceil(10.2))
	fmt.Println(math.Ceil(10.9))
	fmt.Println(math.Round(10.2))
	fmt.Println(math.Round(10.5))
	fmt.Println(math.Min(10.2, 10.6))
	fmt.Println(math.Max(10.2, 10.6))

}
